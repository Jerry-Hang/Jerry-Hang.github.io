# config.env.ps1
#
# 博客服务的环境变量覆盖文件，被 启动博客.ps1 和 看门狗.ps1 读取。
# 不存在时用脚本内的默认值（那是手机 4 核时代的配置，在本机偏保守）。
#
# 本机：Ryzen 9 8940HX，16 核 32 线程，分两个 CCD：
#   CCD0 = 逻辑核 0-15
#   CCD1 = 逻辑核 16-31
#
# 选择绑核范围的考虑：
#   · ComfyUI 出图时会把一个 CCD（16 个逻辑核）吃满做采样
#   · 博客是常驻网络服务，只有突发流量才吃 CPU，平时几乎空转
#   → 让博客独占 CCD1（16-31），ComfyUI 用 CCD0，互不干扰
#   → 如果你用 Process Lasso 给 ComfyUI 指定了别的核心，改这里的 $BLOG_CPUS 避开即可
#
# 改完需要重启服务生效：
#   Get-Process blog_server | Stop-Process -Force     # 看门狗 15 秒内会自动拉起

# Tokio 工作线程数。博客是 IO 密集（静态文件 + SQLite），不需要等于核数。
# 手机端原本是 4，本机给 8 足够；调到 16 也不会有明显收益。
$BLOG_WORKERS = '8'

# 绑定到哪些逻辑核。
# 默认值 '0-3' 是手机 4 核 A520 的配置，在本机只用了 12.5% 的核心。
$BLOG_CPUS = '16-31'

# 并发上限。超限返回 503 并记为 blocked。
# 2400 是原项目按手机内存定的；本机 15.2GB 内存可以给同样的值。
$BLOG_MAX_CONCURRENT = '2400'

# 监听地址。
#   前台 (BLOG_EXT_ADDR)   : 0.0.0.0 表示所有网卡都能访问（局域网 + 隧道）
#   后台 (BLOG_LOCAL_ADDR) : 只绑 127.0.0.1，管理端不对外暴露
$BLOG_EXT_ADDR   = '0.0.0.0:8090'
$BLOG_LOCAL_ADDR = '127.0.0.1:8091'
